// Builds st-01.postman_collection.json: the six-step lifecycle from docs/experiments/st-01/design.md.
// Assertions encode the CLEAN contract; after each step a fresh GET (pm.sendRequest) checks the persisted state.
// Usage (from project root): node docs/experiments/st-01/postman/build-collection.js
const fs = require('fs');
const path = require('path');

const persistedCheck = (expected) => [
  `pm.sendRequest({ url: pm.collectionVariables.get("baseUrl") + "/api/orders/" + pm.collectionVariables.get("orderId"), method: "GET", header: { Accept: "application/json" } }, (err, res) => {`,
  `  pm.test("persisted status is ${expected} (fresh GET)", () => {`,
  `    pm.expect(err).to.eql(null);`,
  `    pm.expect(res.code).to.eql(200);`,
  `    pm.expect(res.json().status).to.eql("${expected}");`,
  `  });`,
  `});`,
];

const patchStep = (name, target, tests) => ({
  name,
  request: {
    method: 'PATCH',
    header: [{ key: 'Content-Type', value: 'application/json' }, { key: 'Accept', value: 'application/json' }],
    url: '{{baseUrl}}/api/orders/{{orderId}}/status',
    body: { mode: 'raw', raw: JSON.stringify({ status: target }) },
  },
  event: [{ listen: 'test', script: { type: 'text/javascript', exec: tests } }],
});

const allowed = (target, extra = []) => [
  `pm.test("status is 200", () => pm.response.to.have.status(200));`,
  `pm.test("response status is ${target}", () => pm.expect(pm.response.json().status).to.eql("${target}"));`,
  ...extra,
  ...persistedCheck(target),
];

const collection = {
  info: {
    name: 'ST-01 lifecycle',
    description: 'Six-step sequence from docs/experiments/st-01/design.md. Generated by build-collection.js; do not edit by hand.',
    schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
  },
  variable: [{ key: 'baseUrl', value: 'http://localhost:8080' }, { key: 'orderId', value: '' }],
  item: [
    {
      name: '1 Create order',
      request: {
        method: 'POST',
        header: [{ key: 'Content-Type', value: 'application/json' }, { key: 'Accept', value: 'application/json' }],
        url: '{{baseUrl}}/api/orders',
        body: { mode: 'raw', raw: '{"ownerUserId": 7, "total": 49.99}' },
      },
      event: [{ listen: 'test', script: { type: 'text/javascript', exec: [
        `pm.test("status is 201", () => pm.response.to.have.status(201));`,
        `pm.test("response status is CREATED", () => pm.expect(pm.response.json().status).to.eql("CREATED"));`,
        `pm.collectionVariables.set("orderId", pm.response.json().id);`,
        ...persistedCheck('CREATED'),
      ] } }],
    },
    patchStep('2 PAID', 'PAID', allowed('PAID')),
    patchStep('3 SHIPPED', 'SHIPPED', allowed('SHIPPED')),
    patchStep('4 DELIVERED', 'DELIVERED', allowed('DELIVERED')),
    patchStep('5 COMPLETED', 'COMPLETED', allowed('COMPLETED', [
      `pm.test("completedAt is set", () => pm.expect(pm.response.json().completedAt).to.be.a("string"));`,
    ])),
    patchStep('6 CANCELLED (must be rejected)', 'CANCELLED', [
      `pm.test("COMPLETED -> CANCELLED is rejected with 409", () => pm.response.to.have.status(409));`,
      ...persistedCheck('COMPLETED'),
    ]),
  ],
};

const out = path.join(__dirname, 'st-01.postman_collection.json');
fs.writeFileSync(out, JSON.stringify(collection, null, 2) + '\n');
console.log(`wrote ${out}`);
