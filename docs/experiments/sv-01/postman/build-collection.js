// Builds sv-01.postman_collection.json from docs/openapi-baseline.json so the schema assertion uses the
// baseline's own Order schema. Annotation-only keywords (description, example, readOnly) are dropped because
// they do not affect validation. The OpenAPI-specific `format: int64` is also dropped: Postman's validator
// rejects it as an unknown format (attempt 1), and the schema-only Ajv run ignores it, so dropping it keeps
// the two tools equivalent. Usage (from project root): node docs/experiments/sv-01/postman/build-collection.js
const fs = require('fs');
const path = require('path');

const spec = JSON.parse(fs.readFileSync('docs/openapi-baseline.json', 'utf8'));
const dropped = (k, x) => ['description', 'example', 'readOnly'].includes(k) || (k === 'format' && x === 'int64');
const strip = v => Array.isArray(v) ? v.map(strip) : (v && typeof v === 'object')
  ? Object.fromEntries(Object.entries(v).filter(([k, x]) => !dropped(k, x)).map(([k, x]) => [k, strip(x)]))
  : v;
const orderSchema = strip(spec.components.schemas.Order);

const tests = [
  `const orderSchema = ${JSON.stringify(orderSchema)};`,
  `pm.test("status is 201", () => pm.response.to.have.status(201));`,
  `pm.test("total is a JSON number", () => pm.expect(typeof pm.response.json().total).to.eql("number"));`,
  `pm.test("body matches the baseline Order schema", () => pm.response.to.have.jsonSchema(orderSchema));`,
];

const collection = {
  info: {
    name: 'SV-01 total type',
    description: 'One request from docs/experiments/sv-01/design.md. Generated by build-collection.js; do not edit by hand.',
    schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
  },
  variable: [{ key: 'baseUrl', value: 'http://localhost:8080' }],
  item: [{
    name: 'Create order',
    request: {
      method: 'POST',
      header: [{ key: 'Content-Type', value: 'application/json' }, { key: 'Accept', value: 'application/json' }],
      url: '{{baseUrl}}/api/orders',
      body: { mode: 'raw', raw: '{"ownerUserId": 7, "total": 49.99}' },
    },
    event: [{ listen: 'test', script: { type: 'text/javascript', exec: tests } }],
  }],
};

const out = path.join(__dirname, 'sv-01.postman_collection.json');
fs.writeFileSync(out, JSON.stringify(collection, null, 2) + '\n');
console.log(`wrote ${out}`);
console.log(`Order schema used: ${JSON.stringify(orderSchema)}`);
